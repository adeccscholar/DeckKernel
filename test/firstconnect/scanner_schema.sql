-- Reference schema for the FirstConnection image storage separation.
-- This file is documentation; EnsureSchema implements the executable DDL.
--
-- PERMANENT: never DROP/TRUNCATE during FirstConnection model rebuilds.
CREATE SCHEMA IF NOT EXISTS deckkernel_cache;
CREATE TABLE IF NOT EXISTS deckkernel_cache.scryfall_images (
   url text PRIMARY KEY,
   image_data bytea NOT NULL,
   sha256 text NOT NULL CHECK (length(sha256)=64),
   media_type text NOT NULL,
   cached_at timestamptz NOT NULL DEFAULT now(),
   CHECK (octet_length(image_data)>0)
);

-- DISPOSABLE MODEL: regenerated by FirstConnection after dropping only model tables.
CREATE TABLE deckkernel_test.scryfall_image_assets (
   id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
   image_url text NOT NULL UNIQUE,
   image_kind text NOT NULL DEFAULT 'art_crop',
   illustration_id text,
   sha256 text,
   media_type text,
   image_data bytea,
   downloaded_at timestamptz,
   CHECK (sha256 IS NULL OR length(sha256)=64)
);
CREATE TABLE deckkernel_test.scryfall_card_image_variants (
   card_id integer NOT NULL,
   face_id integer NOT NULL,
   variant text NOT NULL,
   asset_id bigint NOT NULL REFERENCES deckkernel_test.scryfall_image_assets(id),
   PRIMARY KEY (card_id,face_id,variant),
   FOREIGN KEY (card_id,face_id) REFERENCES deckkernel_test.scryfall_card_faces(card_id,face_id)
);
CREATE INDEX ix_scryfall_card_image_variants_asset
   ON deckkernel_test.scryfall_card_image_variants(asset_id);
CREATE TABLE deckkernel_test.scryfall_image_features (
   asset_id bigint PRIMARY KEY REFERENCES deckkernel_test.scryfall_image_assets(id) ON DELETE CASCADE,
   algorithm text NOT NULL,
   algorithm_version integer NOT NULL,
   perceptual_hash bit(64),
   orb_descriptors bytea,
   orb_keypoint_count integer NOT NULL DEFAULT 0,
   calculated_at timestamptz NOT NULL DEFAULT now()
);
